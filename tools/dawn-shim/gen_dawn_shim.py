#!/usr/bin/env python3
"""Generates the wgpu* entry points of a JSUI built against Dawn's headers
without linking Dawn (JSUI_GRAPHITE_DAWN).

Every function webgpu.h declares becomes a hidden trampoline that calls
through one slot of a process-wide table. Nothing is looked up when a
trampoline runs: the table is filled up front, all or nothing, in one of two
ways:

  jsui_dawn_fill_from_get_proc(gp)  through the host's wgpuGetProcAddress
                                    (jsui_gpu_create_dawn_procs; e.g. the
                                    godot-aw3 fork's WebGPUInterop singleton).
                                    Works whatever the host exports.
  jsui_dawn_fill_from_process()     dlsym(RTLD_DEFAULT) of every name
                                    (jsui_gpu_create_dawn; a host binary that
                                    exports its Dawn's symbols; never on
                                    Windows).

The library therefore links and loads anywhere; the Dawn path is usable only
once the table is complete (jsui_dawn_ready()).

    gen_dawn_shim.py <include>/dawn/webgpu.h <out.c> [<dawn revision>]
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
revision = sys.argv[3] if len(sys.argv) > 3 else ""
if not re.fullmatch(r"[0-9a-f]*", revision):
    sys.exit(f"bad Dawn revision {revision!r}")
decl = re.compile(r"^WGPU_EXPORT (.+?)\b(wgpu\w+)\((.*)\) WGPU_FUNCTION_ATTRIBUTE;$")
fns = []
for line in open(src):
    m = decl.match(line.strip())
    if m:
        fns.append((m.group(1).strip(), m.group(2), m.group(3).strip()))
if not fns:
    sys.exit(f"no wgpu* declarations in {src}")
if "wgpuGetProcAddress" not in [name for _, name, _ in fns]:
    sys.exit(f"no wgpuGetProcAddress in {src}")


def arg_names(params):
    if params in ("", "void"):
        return []
    names = []
    for p in params.split(","):
        names.append(re.findall(r"\w+", p)[-1])
    return names


lines = [
    "// Generated by tools/dawn-shim/gen_dawn_shim.py from " + src.split("/include/")[-1] + ". Do not edit.",
    "#include <stddef.h>",
    "#include <string.h>",
    "#if !defined(_WIN32)",
    "#include <dlfcn.h>",
    "#endif",
    '#include "dawn/webgpu.h"',
    "",
    "#if defined(_WIN32)",
    "#define JSUI_HIDDEN",
    "#else",
    "#define JSUI_HIDDEN __attribute__((visibility(\"hidden\")))",
    "#endif",
    "",
    f"#define JSUI_DAWN_PROC_COUNT {len(fns)}",
    "",
    "static const char* const jsui_dawn_names[JSUI_DAWN_PROC_COUNT] = {",
] + [f'  "{name}",' for _, name, _ in fns] + [
    "};",
    "",
    "// The resolved entry points, index-aligned with jsui_dawn_names. Written",
    "// only as a whole (fill_* below), read by the trampolines.",
    "static WGPUProc jsui_dawn_procs[JSUI_DAWN_PROC_COUNT];",
    "static int jsui_dawn_filled = 0;",
    "",
    f'JSUI_HIDDEN const char* jsui_dawn_header_revision(void) {{ return "{revision}"; }}',
    "JSUI_HIDDEN int jsui_dawn_proc_count(void) { return JSUI_DAWN_PROC_COUNT; }",
    "JSUI_HIDDEN const char* jsui_dawn_proc_name(int i) {",
    "  return i >= 0 && i < JSUI_DAWN_PROC_COUNT ? jsui_dawn_names[i] : NULL;",
    "}",
    "JSUI_HIDDEN void* jsui_dawn_proc(int i) {",
    "  return i >= 0 && i < JSUI_DAWN_PROC_COUNT ? (void*)jsui_dawn_procs[i] : NULL;",
    "}",
    "JSUI_HIDDEN int jsui_dawn_ready(void) { return jsui_dawn_filled; }",
    "",
    "static int jsui_dawn_commit(const WGPUProc* procs, int resolved) {",
    "  if (resolved != JSUI_DAWN_PROC_COUNT) return resolved;  // incomplete: keep the table as it is",
    "  memcpy(jsui_dawn_procs, procs, sizeof(jsui_dawn_procs));",
    "  jsui_dawn_filled = 1;",
    "  return resolved;",
    "}",
    "",
    "// Resolves every entry point through `get_proc` (WGPUProc",
    "// wgpuGetProcAddress(WGPUStringView)). Returns how many resolved; the table",
    "// is replaced only when all of them did (== jsui_dawn_proc_count()).",
    "JSUI_HIDDEN int jsui_dawn_fill_from_get_proc(void* get_proc) {",
    "  WGPUProcGetProcAddress gp = (WGPUProcGetProcAddress)get_proc;",
    "  WGPUProc procs[JSUI_DAWN_PROC_COUNT];",
    "  int resolved = 0;",
    "  if (!gp) return 0;",
    "  for (int i = 0; i < JSUI_DAWN_PROC_COUNT; i++) {",
    "    WGPUStringView name;",
    "    name.data = jsui_dawn_names[i];",
    "    name.length = strlen(jsui_dawn_names[i]);",
    "    // The getter itself, whether or not the host's table lists it.",
    '    procs[i] = strcmp(jsui_dawn_names[i], "wgpuGetProcAddress") == 0 ? (WGPUProc)gp : gp(name);',
    "    if (procs[i]) resolved++;",
    "  }",
    "  return jsui_dawn_commit(procs, resolved);",
    "}",
    "",
    "// The same through the process's exported symbols (dlsym). Every entry point",
    "// of the headers must be there: a host that links Dawn but keeps only the",
    "// functions it calls (dead-stripped) would otherwise crash in the first",
    "// missing one. Always 0 on Windows.",
    "JSUI_HIDDEN int jsui_dawn_fill_from_process(void) {",
    "#if defined(_WIN32)",
    "  return 0;",
    "#else",
    "  WGPUProc procs[JSUI_DAWN_PROC_COUNT];",
    "  int resolved = 0;",
    "  for (int i = 0; i < JSUI_DAWN_PROC_COUNT; i++) {",
    "    procs[i] = (WGPUProc)dlsym(RTLD_DEFAULT, jsui_dawn_names[i]);",
    "    if (procs[i]) resolved++;",
    "  }",
    "  return jsui_dawn_commit(procs, resolved);",
    "#endif",
    "}",
    "",
]
for i, (ret, name, params) in enumerate(fns):
    args = ", ".join(arg_names(params))
    proc = "WGPUProc" + name[len("wgpu"):]
    call = f"(({proc})jsui_dawn_procs[{i}])({args})"
    body = f"return {call};" if ret != "void" else f"{call};"
    lines += [
        f"JSUI_HIDDEN {ret} {name}({params}) {{",
        f"  {body}",
        "}",
    ]
open(out, "w").write("\n".join(lines) + "\n")
print(f"gen_dawn_shim: {len(fns)} entry points -> {out}")
