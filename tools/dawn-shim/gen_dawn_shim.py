#!/usr/bin/env python3
"""Generates the wgpu* entry points for a JSUI built against a Dawn SDK's
headers without linking Dawn (JSUI_GRAPHITE_DAWN).

Every function webgpu.h declares becomes a hidden trampoline that looks the
real entry point up in the process the first time it is called
(dlsym(RTLD_DEFAULT), e.g. the godot-aw3 engine binary, which exports its
statically linked Dawn). The library therefore links and loads anywhere; the
Dawn path is usable only where the host provides Dawn
(jsui_dawn_available()).

    gen_dawn_shim.py <sdk>/include/dawn/webgpu.h <out.c>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
decl = re.compile(r"^WGPU_EXPORT (.+?)\b(wgpu\w+)\((.*)\) WGPU_FUNCTION_ATTRIBUTE;$")
fns = []
for line in open(src):
    m = decl.match(line.strip())
    if m:
        fns.append((m.group(1).strip(), m.group(2), m.group(3).strip()))
if not fns:
    sys.exit(f"no wgpu* declarations in {src}")


def arg_names(params):
    if params in ("", "void"):
        return []
    names = []
    for p in params.split(","):
        names.append(re.findall(r"\w+", p)[-1])
    return names


lines = [
    "// Generated by tools/dawn-shim/gen_dawn_shim.py from " + src.split("/include/")[-1] + ". Do not edit.",
    "#include <dlfcn.h>",
    "#include <stddef.h>",
    '#include "dawn/webgpu.h"',
    "",
    "#define JSUI_HIDDEN __attribute__((visibility(\"hidden\")))",
    "",
    "static void* jsui_dawn_sym(const char* name) { return dlsym(RTLD_DEFAULT, name); }",
    "",
    "// Every entry point of the headers must be in the process. A Godot that",
    "// links Dawn but keeps only the functions it calls (dead-stripped; e.g.",
    "// godot-aw3 before it exported them all) would otherwise crash in the first",
    "// missing one, and such builds also return driver ids rather than webgpu.h",
    "// handles from get_driver_resource.",
    "static const char* const jsui_dawn_names[] = {",
] + [f'  "{name}",' for _, name, _ in fns] + [
    "};",
    "",
    "JSUI_HIDDEN int jsui_dawn_available(void) {",
    "  for (size_t i = 0; i < sizeof(jsui_dawn_names) / sizeof(jsui_dawn_names[0]); i++)",
    "    if (!jsui_dawn_sym(jsui_dawn_names[i])) return 0;",
    "  return 1;",
    "}",
    "",
]
for ret, name, params in fns:
    args = ", ".join(arg_names(params))
    proc = "WGPUProc" + name[len("wgpu"):]
    call = f"fn({args})"
    body = f"return {call};" if ret != "void" else f"{call};"
    lines += [
        f"JSUI_HIDDEN {ret} {name}({params}) {{",
        f"  static {proc} fn = NULL;",
        f'  if (!fn) fn = ({proc})jsui_dawn_sym("{name}");',
        f"  {body}",
        "}",
    ]
open(out, "w").write("\n".join(lines) + "\n")
print(f"gen_dawn_shim: {len(fns)} entry points -> {out}")
